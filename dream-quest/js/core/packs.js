/* Dream Quest — content-pack loader.
 *
 * Quests, stories, word lists, skill ladders, bands and companions all arrive as JSON
 * "content packs" listed in a server manifest. New packs (or new versions) reach the app
 * without an app rebuild:
 *
 *   1. fetch  <packBase>/manifest.json         (fresh, no-store)
 *   2. for each listed pack: use the cached copy if its version matches, else fetch it
 *   3. validate it, check app version + required quest engines, cache it on the device
 *   4. register it: world packs -> bands/areas/companions, skill packs -> skill graph
 *
 * Offline / first-run / file:// fall back to the last cached copy, then to the packs
 * bundled with the app (js/packs-bundled.js, generated by tools/bundle-packs.mjs).
 */
(function () {
  'use strict';
  const DQ = window.DQ, U = DQ.util;
  const CACHE = 'dreamquest.pack.';

  DQ.Engines = DQ.Engines || {};

  function validate(p) {
    const errs = [];
    if (!p || typeof p !== 'object') return ['not an object'];
    if (p.format !== 1) errs.push('unknown format ' + p.format);
    if (!p.id) errs.push('missing id');
    if (!p.version) errs.push('missing version');
    if (!['world', 'skills'].includes(p.kind)) errs.push('unknown kind ' + p.kind);
    if (p.kind === 'world' && !Array.isArray(p.bands)) errs.push('world pack without bands');
    if (p.kind === 'skills') {
      if (!Array.isArray(p.skills)) errs.push('skills pack without skills');
      else p.skills.forEach((s) => {
        if (!s.id && !s.extends) errs.push('skill without id');
        if (!Array.isArray(s.levels) || !s.levels.every((l) => typeof l.n === 'number' && l.params)) errs.push('bad levels in ' + (s.id || s.extends));
      });
    }
    return errs;
  }

  async function fetchJSON(url) {
    if (location.protocol === 'file:') throw new Error('file:// cannot fetch');
    const r = await fetch(url, { cache: 'no-store' });
    if (!r.ok) throw new Error('HTTP ' + r.status);
    return r.json();
  }

  function cached(id) {
    const raw = U.lsGet(CACHE + id);
    if (!raw) return null;
    try { return JSON.parse(raw); } catch (e) { return null; }
  }

  const Packs = (DQ.Packs = {
    installed: {},   // id -> { pack, source: 'server'|'cache'|'bundled', updated: bool }
    skipped: [],     // { id, reason }
    manifestSource: null,
    lastCheck: null,

    get(id) { return this.installed[id] && this.installed[id].pack; },
    list() { return Object.values(this.installed); },

    /** Merge a data field across all installed packs: arrays concatenate, objects merge. */
    data(field) {
      let out;
      for (const { pack } of this.list()) {
        const v = pack.data && pack.data[field];
        if (v == null) continue;
        if (Array.isArray(v)) out = (out || []).concat(v);
        else if (typeof v === 'object') out = Object.assign(out || {}, v);
        else out = v;
      }
      return out;
    },

    async load(onProgress) {
      const bundled = window.DQ_BUNDLED || { manifest: null, packs: {} };
      let manifest = null;
      try {
        manifest = await fetchJSON(DQ.config.packBase + 'manifest.json');
        this.manifestSource = 'server';
        U.lsSet(CACHE + '@manifest', JSON.stringify(manifest));
      } catch (e) {
        manifest = cached('@manifest');
        this.manifestSource = manifest ? 'cache' : 'bundled';
        if (!manifest) manifest = bundled.manifest;
      }
      if (!manifest) throw new Error('No content manifest available');

      this.installed = {}; this.skipped = [];
      const entries = manifest.packs.slice().sort((a, b) => (a.band || 0) - (b.band || 0));
      let i = 0;
      for (const entry of entries) {
        onProgress && onProgress(++i / entries.length, entry.id);
        if (entry.minApp && U.cmpVersion(entry.minApp, DQ.APP_VERSION) > 0) {
          this.skipped.push({ id: entry.id, reason: 'Needs app ' + entry.minApp + ' or newer' });
          continue;
        }
        let pack = null, source = null, updated = false;
        const have = cached(entry.id);
        if (have && have.version === entry.version) { pack = have; source = 'cache'; }
        else {
          try {
            const fresh = await fetchJSON(DQ.config.packBase + entry.file);
            const errs = validate(fresh);
            if (errs.length) throw new Error(errs.join('; '));
            pack = fresh; source = 'server'; updated = !!have;
            U.lsSet(CACHE + entry.id, JSON.stringify(fresh));
          } catch (e) {
            if (have && !validate(have).length) { pack = have; source = 'cache'; }
            else if (bundled.packs[entry.id]) { pack = bundled.packs[entry.id]; source = 'bundled'; }
          }
        }
        if (!pack) { this.skipped.push({ id: entry.id, reason: 'Could not download' }); continue; }
        const missing = (pack.engines || []).filter((e) => !DQ.Engines[e]);
        if (missing.length) { this.skipped.push({ id: entry.id, reason: 'Needs quest type: ' + missing.join(', ') + ' (app update)' }); continue; }
        this.installed[pack.id] = { pack, source, updated };
      }
      this.lastCheck = new Date();
      this.register();
      return { updated: this.list().filter((x) => x.updated).map((x) => x.pack), skipped: this.skipped };
    },

    register() {
      DQ.Skills.reset();
      for (const { pack } of this.list()) {
        if (pack.kind === 'world') DQ.World = pack;
        else if (pack.kind === 'skills') DQ.Skills.addPack(pack);
      }
      if (!DQ.World) throw new Error('World pack missing');
    },

    validate,
  });
})();
