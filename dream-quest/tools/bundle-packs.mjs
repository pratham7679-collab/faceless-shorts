#!/usr/bin/env node
// Bundle packs/*.json into js/packs-bundled.js so the app also works offline and from file://.
// Run after editing any pack:  node tools/bundle-packs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(readFileSync(join(root, 'packs/manifest.json'), 'utf8'));
const packs = {};
for (const e of manifest.packs) {
  const p = JSON.parse(readFileSync(join(root, 'packs', e.file), 'utf8'));
  if (p.id !== e.id || p.version !== e.version) throw new Error(`${e.file}: manifest says ${e.id}@${e.version}, file says ${p.id}@${p.version}`);
  packs[p.id] = p;
}
const out = `/* GENERATED by tools/bundle-packs.mjs — do not edit. Offline fallback copy of packs/. */\nwindow.DQ_BUNDLED = ${JSON.stringify({ manifest, packs })};\n`;
writeFileSync(join(root, 'js/packs-bundled.js'), out);
console.log(`bundled ${Object.keys(packs).length} packs, ${(out.length / 1024).toFixed(1)} KB`);
